function ne_lek(usd) {
  return Math.round((usd * KURSI) / 50) * 50;
}

function ndertoPershkrimin(paragrafi, pikat) {
  return `${paragrafi}\n\n${pikat.map((p) => `• ${p}`).join("\n")}`;
}

async function merrKategorine(emri) {
  const ekzistuese = await prisma.category.findFirst({ where: { emri } });
  if (ekzistuese) return ekzistuese;
  return prisma.category.create({ data: { emri } });
}

async function merrPerberesin(celesi) {
  const [emri, perfitimi] = PERBERESIT[celesi];
  const ekzistues = await prisma.ingredient.findFirst({ where: { emri } });
  if (ekzistues) {
    return prisma.ingredient.update({
      where: { id: ekzistues.id },
      data: { perfitimi },
    });
  }
  return prisma.ingredient.create({ data: { emri, perfitimi } });
}

async function main() {
  let shtuar = 0;
  let perditesuar = 0;

  for (const [
    marka,
    emri,
    kategoria,
    cmimiUsd,
    tipet,
    perberesit,
    paragrafi,
    pikat,
    promovim,
  ] of PRODUKTET) {
    const emriPlote = `${marka} ${emri}`;
    const pershkrimi = ndertoPershkrimin(paragrafi, pikat);
    const cmimi = ne_lek(cmimiUsd);
    const kat = await merrKategorine(kategoria);

    const lidhje = [];
    for (const celesi of perberesit) {
      const p = await merrPerberesin(celesi);
      lidhje.push({ ingredient: { connect: { id: p.id } } });
    }

    const ekziston = await prisma.product.findFirst({
      where: { emri: emriPlote },
    });

    if (ekziston) {
      await prisma.product.update({
        where: { id: ekziston.id },
        data: {
          pershkrimi,
          cmimi,
          marka,
          tipiLekurePershtatshem: JSON.stringify(tipet),
          nePromovim: promovim,
          kategoria: { connect: { id: kat.id } },
          ingredients: { deleteMany: {}, create: lidhje },
        },
      });
      perditesuar++;
    } else {
      await prisma.product.create({
        data: {
          emri: emriPlote,
          pershkrimi,
          cmimi,
          marka,
          stoku: 20 + Math.floor(Math.random() * 80),
          tipiLekurePershtatshem: JSON.stringify(tipet),
          nePromovim: promovim,
          kategoria: { connect: { id: kat.id } },
          ingredients: { create: lidhje },
        },
      });
      shtuar++;
    }
  }

  console.log(`U shtuan ${shtuar} produkte, u përditësuan ${perditesuar}`);
}

if (require.main === module) {
  main()
    .catch((e) => {
      console.error(e);
      process.exit(1);
    })
    .finally(() => prisma.$disconnect());
}

module.exports = { PRODUKTET, PERBERESIT, ne_lek };
